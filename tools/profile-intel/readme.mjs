// Profile README rendering. The pipeline owns exactly three marked blocks and
// never touches a byte outside them:
//   profile-intel:recent   "Latest engineering work", inserted before "## Path"
//   profile-intel:updated  the date the generated content last changed, right after it
//   profile-intel:stack    "In active use", under the existing stack image
// A block always ends with a blank line, so stripping blocks from the output
// gives back the original README exactly (verified on every run).

import { CONFIG } from './config.mjs';
import { activeStack, publicEvidence, recentEntries, repoLink } from './selection.mjs';
import { detectEol, humanDate, toLf, withEol } from './util.mjs';

export const BLOCKS = ['recent', 'updated', 'stack'];
const start = (name) => `<!-- profile-intel:${name}:start -->`;
const end = (name) => `<!-- profile-intel:${name}:end -->`;

const TOOL_URL = 'https://github.com/kpdagrt22/kpdagrt22/tree/main/tools/profile-intel';

/** Escape text that did not come from the owner (commit titles, repo descriptions). */
export function mdEscape(text) {
  return String(text ?? '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/([\\`*_[\]<>|~])/g, '\\$1');
}

function mdLink(text, url) {
  return url ? `[${text}](${url})` : text;
}

const SEP = '&nbsp;·&nbsp;';

export function renderRecent(manifest, cfg = CONFIG) {
  const entries = recentEntries(manifest, cfg);
  const lines = [
    '## Latest engineering work',
    '',
    '<sub>Meaningful changes from my GitHub activity, refreshed weekly by an automated job that filters out noise (bots, merges, formatting, lockfiles, small docs edits, reverts). Public work links to its commit or pull request; private repositories are named without links or code.</sub>',
    '',
  ];
  if (entries.length === 0) {
    lines.push('No meaningful activity recorded yet.');
    return lines.join('\n');
  }
  for (const e of entries) {
    // Owner-approved names are used as written; generated names are escaped.
    const name = e.source === 'manual' ? e.name : mdEscape(e.name);
    const head = [`**${mdLink(name, e.liveUrl)}**`];
    const repo = repoLink(e);
    const repoLabel = e.category === 'upstream' ? 'upstream' : e.category === 'fork' ? 'fork' : 'source';
    if (repo && repo !== e.liveUrl) head.push(mdLink(repoLabel, repo));
    if (e.visibility === 'private') head.push('private repository');
    if (e.source === 'manual' && e.statusText) head.push(e.statusText);
    else if (e.status) head.push(e.status.replace('-', ' '));
    head.push(`last change ${humanDate(e.lastMeaningfulActivity)}`);
    let line = `- ${head.join(SEP)}`;
    const detail = [];
    if (e.source === 'auto' && e.shortDescription) detail.push(mdEscape(e.shortDescription));
    const ev = publicEvidence(e, 3);
    if (ev.length) detail.push(`Recent: ${ev.map((x) => mdLink(mdEscape(x.title), x.url)).join(' · ')}`);
    const tech = Object.keys(e.technologyEvidence ?? {}).sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));
    if (tech.length) detail.push(`<sub>${tech.map(mdEscape).join(', ')}</sub>`);
    if (detail.length) line += `<br>\n  ${detail.join('<br>\n  ')}`;
    lines.push(line);
  }
  return lines.join('\n');
}

export function renderStack(manifest, cfg = CONFIG) {
  const s = activeStack(manifest, cfg);
  if (!s.anchor || (s.languages.length === 0 && s.frameworks.length === 0)) {
    return '**In active use:** no technology evidence recorded yet.';
  }
  const out = [
    `**In active use** <sub>(from projects with meaningful GitHub activity in the ${cfg.activeWindowDays} days to ${humanDate(s.anchor)}: languages by GitHub's byte count, frameworks only when a dependency manifest declares them and the code imports them)</sub><br>`,
  ];
  const parts = [];
  if (s.languages.length) parts.push(`Languages: ${s.languages.map((t) => mdEscape(t.name)).join(', ')}`);
  if (s.frameworks.length) parts.push(`Frameworks and libraries: ${s.frameworks.map((t) => mdEscape(t.name)).join(', ')}`);
  out.push(parts.join('<br>\n'));
  return out.join('\n');
}

export function renderUpdated(today) {
  return `<sub>Latest engineering work and In active use last changed on ${humanDate(today)}, generated by <a href="${TOOL_URL}">profile-intel</a> from GitHub activity.</sub>`;
}

/** Locate a block: { from, to, inner } where [from, to) spans start marker..end marker. */
export function findBlock(text, name) {
  const s = start(name);
  const e = end(name);
  const i = text.indexOf(s);
  const j = text.indexOf(e);
  if (i === -1 && j === -1) return null;
  if (i === -1 || j === -1 || j < i) throw new Error(`README: the ${name} block markers are incomplete or out of order`);
  if (text.indexOf(s, i + 1) !== -1 || text.indexOf(e, j + 1) !== -1) throw new Error(`README: the ${name} block markers appear more than once`);
  const innerStart = i + s.length + 1; // after the newline that follows the start marker
  const innerEnd = j - 1; // before the newline that precedes the end marker
  return { from: i, to: j + e.length, inner: innerEnd >= innerStart ? text.slice(innerStart, innerEnd) : '' };
}

const blockText = (name, inner) => `${start(name)}\n${inner}\n${end(name)}`;

/** Remove every generated block (and the blank line that follows it). */
export function stripBlocks(text) {
  return text.replace(/<!-- profile-intel:(\w+):start -->[\s\S]*?<!-- profile-intel:\1:end -->\n?\n?/g, '');
}

function insertAt(text, index, chunk) {
  return text.slice(0, index) + chunk + text.slice(index);
}

function stackAnchor(text) {
  const img = text.indexOf('assets/stack-light.svg');
  if (img === -1) throw new Error('README: cannot find the stack image (assets/stack-light.svg) to place the In active use block under');
  const close = text.indexOf('</picture>\n', img);
  if (close === -1) throw new Error('README: the stack image <picture> is not closed');
  let at = close + '</picture>\n'.length;
  if (text[at] === '\n') at += 1; // keep the existing blank line above the block
  return at;
}

function recentAnchor(text) {
  const m = /^## Path[ \t]*$/m.exec(text);
  if (!m) throw new Error('README: cannot find the "## Path" heading to place Latest engineering work before');
  return m.index;
}

function setBlock(text, name, inner, anchorFn) {
  const b = findBlock(text, name);
  if (b) return text.slice(0, b.from) + blockText(name, inner) + text.slice(b.to);
  return insertAt(text, anchorFn(text), `${blockText(name, inner)}\n\n`);
}

/**
 * Apply the generated blocks to a README. Returns
 * { text, changed, blocksChanged: [names] }.
 * The "updated" block changes only when recent or stack content changes.
 */
export function updateReadme(original, { recent, stack, today }) {
  const eol = detectEol(original);
  if (eol === '\r\n' && /(^|[^\r])\n/.test(original)) throw new Error('README has mixed line endings; refusing to edit it');
  const lf = toLf(original);
  const old = { recent: findBlock(lf, 'recent'), stack: findBlock(lf, 'stack'), updated: findBlock(lf, 'updated') };
  const blocksChanged = [];
  if (old.recent?.inner !== recent) blocksChanged.push('recent');
  if (old.stack?.inner !== stack) blocksChanged.push('stack');

  let text = lf;
  text = setBlock(text, 'recent', recent, recentAnchor);
  const updatedInner = blocksChanged.length || !old.updated ? renderUpdated(today) : old.updated.inner;
  if (old.updated?.inner !== updatedInner) blocksChanged.push('updated');
  text = setBlock(text, 'updated', updatedInner, (t) => {
    const r = findBlock(t, 'recent');
    return r.to + 2; // after "<!-- recent:end -->\n\n"
  });
  text = setBlock(text, 'stack', stack, stackAnchor);

  if (stripBlocks(text) !== stripBlocks(lf)) {
    throw new Error('README: generated output would change content outside the profile-intel markers; refusing');
  }
  const out = withEol(text, eol);
  return { text: out, changed: out !== original, blocksChanged };
}

/** The generated blocks only, for the output scanner. */
export function generatedBlocks(text) {
  const lf = toLf(text);
  return BLOCKS.map((name) => findBlock(lf, name)).filter(Boolean).map((b) => b.inner).join('\n');
}
